/* ------------------------------------------------------ shaping and writing */

function expDoc(row, admin, serverNow) {
  const e = row.exp;
  const links = (e.links || []).map(url).filter(Boolean);
  if (links.length > 8) die("more than 8 reference links on " + row.id);
  const out = {
    title: clip(e.title, MAX_TITLE, "title"),
    detail: clip(e.detail, MAX_LINE, "detail"),
    status: pick(e.status, STATUSES, "status"),
    hypothesis: clip(e.hypothesis, MAX_PROSE, "hypothesis"),
    trying: clip(e.trying, MAX_PROSE, "trying"),
    metric: pick(e.metric, METRIC_KEYS, "metric"),
    decision: clip(e.decision, MAX_PROSE, "decision"),
    inspiration: clip(e.inspiration, MAX_PROSE, "inspiration"),
    links: links,
    endBy: day(e.endBy),
    startedAt: e.startedAt ? admin.firestore.Timestamp.fromDate(e.startedAt) : null,
    endedAt: e.endedAt ? admin.firestore.Timestamp.fromDate(e.endedAt) : null,
    outcome: clip(e.outcome, MAX_PROSE, "outcome"),
    /* Empty, and stamped by nobody. See the note at the top: a seeded opinion
       signed by no one is the exact thing the two-layer design forbids. */
    analysis: "",
    analysisBy: null,
    analysisByName: null,
    analysisAt: null,
    analysisRequestedAt: null,
    order: Number(e.order) || 0,
    createdAt: serverNow,
    updatedAt: serverNow,
    /* `updatedBy` must be a string the rules would accept from a browser; the
       admin SDK does not have a uid. "seed" is what tools/seed-tasks.js put on
       130 rows of the task board for the same reason, and the UI is required
       to read it as "the seeding script" rather than as a person. */
    updatedBy: "seed"
  };
  if (!out.title) die("an experiment needs a title: " + row.id);
  return out;
}

function reelDoc(r, admin, serverNow) {
  const MAXES = {
    views: 1e10, reach: 1e10, likes: 1e10, comments: 1e10, shares: 1e10,
    saves: 1e10, profileTaps: 1e10, avgWatch: 86400, completion: 100, threeSec: 100
  };
  const out = {
    story: clip(r.story, MAX_STORY, "story"),
    url: url(r.url),
    platform: pick(r.platform, PLATFORMS, "platform"),
    variant: pick(r.variant, VARIANTS, "variant"),
    format: clip(r.format, 24, "format"),
    postedAt: r.postedAt ? admin.firestore.Timestamp.fromDate(r.postedAt) : null,
    measuredAt: r.measuredAt ? admin.firestore.Timestamp.fromDate(r.measuredAt) : null,
    cover: url(r.cover),
    coverPath: clip(r.coverPath, 300, "coverPath"),
    retention: (r.retention || []).map((p) => ({
      second: numOrNull(p.second, 0, 86400, "retention second"),
      percentage: numOrNull(p.percentage, 0, 100, "retention percentage")
    })),
    /* "manual", because every one of these numbers is the kind a person types
       off a phone screen. "api" exists in the enum for a writer that is not a
       person; nothing fetches anything. */
    source: pick(r.source || "manual", SOURCES, "source"),
    analysis: "",
    analysisBy: null,
    analysisByName: null,
    analysisAt: null,
    order: Number(r.order) || 0,
    createdAt: serverNow,
    updatedAt: serverNow,
    updatedBy: "seed"
  };
  if (!out.story) die("a reel needs a story name");
  if (out.retention.length > 40) die("more than 40 retention points on " + r.id);
  for (const k of METRIC_KEYS) out[k] = numOrNull(r[k], 0, MAXES[k], k);

  /* THE ONE RULE, CHECKED ON THE SEED TOO. A seeded row that broke the
     72-hour rule would teach the wrong thing on the first screen anybody
     looks at, and it would do it with the authority of something that came
     with the product. */
  if (out.postedAt && out.measuredAt) {
    const gap = (out.measuredAt.toMillis() - out.postedAt.toMillis()) / H;
    if (gap < MEASURE_HOURS) {
      die(`${r.id} is measured ${gap.toFixed(1)}h after posting; the board reads every ` +
          `reel at ${MEASURE_HOURS}h and a seeded row must not be the exception`);
    }
  }
  return out;
}

async function main() {
  if (!fs.existsSync(KEY_PATH)) {
    die("no service-account key at " + KEY_PATH + " — ask Hassan for one. " +
        "It lives outside the repo and must never be committed.");
  }
  let key;
  try { key = JSON.parse(fs.readFileSync(KEY_PATH, "utf8")); }
  catch (e) { die("could not read " + KEY_PATH + ": " + e.message); }
  if (!key || key.project_id !== PROJECT) {
    die("that key is for project " + JSON.stringify(key && key.project_id) + ", not " + PROJECT);
  }

  const admin = require("firebase-admin");   // resolves from tools/node_modules
  if (!admin.apps.length) {
    admin.initializeApp({ credential: admin.credential.cert(key), projectId: PROJECT });
  }
  const db = admin.firestore();
  const serverNow = admin.firestore.Timestamp.now();

  console.log(`\n  project   ${PROJECT}${DRY ? "   (DRY RUN — nothing is written)" : ""}`);
  console.log(`  writing   ${ROWS.length} experiments and ` +
              `${ROWS.reduce((n, r) => n + r.reels.length, 0)} reels\n`);

  let created = 0, skipped = 0, reelsCreated = 0, reelsSkipped = 0;

  for (const row of ROWS) {
    const doc = expDoc(row, admin, serverNow);
    const ref = db.collection(EXPS).doc(row.id);

    if (DRY) {
      const snap = await ref.get();
      console.log(`  ${snap.exists ? "skip  " : "create"}  ${EXPS}/${row.id}   ${doc.title}`);
      snap.exists ? skipped++ : created++;
    } else {
      try {
        await ref.create(doc);            /* create(), never set() — see the header */
        created++;
        console.log(`  create  ${EXPS}/${row.id}   ${doc.title}`);
      } catch (e) {
        if (String(e && e.code) === "6" || /ALREADY_EXISTS/i.test(String(e))) {
          skipped++;
          console.log(`  skip    ${EXPS}/${row.id}   already there, left alone`);
        } else { die("could not write " + row.id + ": " + (e && e.message)); }
      }
    }

    for (const r of row.reels) {
      const rd = reelDoc(r, admin, serverNow);
      const rref = ref.collection(REELS).doc(r.id);
      if (DRY) {
        const s2 = await rref.get();
        console.log(`            ${s2.exists ? "skip  " : "create"}  ${REELS}/${r.id}   ${rd.story}`);
        s2.exists ? reelsSkipped++ : reelsCreated++;
      } else {
        try {
          await rref.create(rd);
          reelsCreated++;
          console.log(`            create  ${REELS}/${r.id}   ${rd.story}`);
        } catch (e) {
          if (String(e && e.code) === "6" || /ALREADY_EXISTS/i.test(String(e))) {
            reelsSkipped++;
            console.log(`            skip    ${REELS}/${r.id}   already there`);
          } else { die("could not write reel " + r.id + ": " + (e && e.message)); }
        }
      }
    }
  }

  console.log(`\n  ${EXPS}   ${DRY ? "would create" : "created"} ${created}, skipped ${skipped}`);
  console.log(`  ${REELS}               ${DRY ? "would create" : "created"} ${reelsCreated}, skipped ${reelsSkipped}`);
  console.log(`\n  NOTE: firestore.rules for ${EXPS} may not be deployed yet. The admin`);
  console.log(`  SDK writes regardless; the BROWSER reads nothing until they ship.\n`);
  process.exit(0);
}

main().catch((e) => die(e && e.stack ? e.stack : String(e)));
