function die(msg) { console.error("\n  " + msg + "\n"); process.exit(1); }

function clip(v, n, what) {
  const s = (v == null ? "" : String(v)).replace(/\s+/g, " ").trim();
  if (s.length > n) die(`${what} is ${s.length} characters; the rules cap it at ${n}`);
  return s;
}
/* EXACT FIRST, then case-insensitively — because the metric keys are the one
   list here that is NOT all lowercase. `threeSec` and `profileTaps` are field
   names, not enum words, and lowercasing them (which is what this function did
   at first, and what it refused loudly rather than silently coercing) turns a
   valid metric into one the rules would deny. Matching exactly first means a
   correctly-spelled value is never touched; the fallback only exists so that
   "Instagram" and "instagram" are the same platform. */
function pick(v, list, what) {
  const raw = String(v == null ? "" : v).trim();
  if (list.indexOf(raw) !== -1) return raw;
  const lower = raw.toLowerCase();
  for (const one of list) { if (one.toLowerCase() === lower) return one; }
  die(`"${raw}" is not a valid ${what}. The rules accept: ${list.join(", ")}`);
}
/* "" or one real calendar day, round-tripped through UTC so "2026-02-31" is
   refused here rather than accepted by the regex in firestore.rules, which
   cannot count the days in a month. */
function day(v) {
  const s = String(v == null ? "" : v).trim();
  if (!s) return "";
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(s);
  if (!m) die(`"${s}" is not a calendar day. Use YYYY-MM-DD, or "" for none.`);
  const y = +m[1], mo = +m[2], d = +m[3];
  const t = new Date(Date.UTC(y, mo - 1, d));
  if (t.getUTCFullYear() !== y || t.getUTCMonth() !== mo - 1 || t.getUTCDate() !== d) {
    die(`"${s}" is not a day that exists.`);
  }
  return s;
}
/* An https:// URL, or "". The same gate the client applies, applied again
   here, because the admin SDK does not pass through the rules that would
   otherwise refuse a `javascript:` string. */
function url(v) {
  const s = String(v == null ? "" : v).replace(/[\u0000-\u001F\u007F]+/g, "").trim();
  if (!s) return "";
  if (s.toLowerCase().indexOf("https://") !== 0) die(`"${s}" is not an https:// URL`);
  return s;
}
function numOrNull(v, lo, hi, what) {
  if (v === null || v === undefined || v === "") return null;
  const n = Number(v);
  if (!isFinite(n)) die(`${what} is not a number: ${JSON.stringify(v)}`);
  if (n < lo || n > hi) die(`${what} is out of range (${lo}–${hi}): ${n}`);
  return Math.round(n * 10) / 10;
}

