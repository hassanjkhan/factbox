#!/usr/bin/env node
/* ==========================================================================
   Factbox — put TWO example experiments on the reel experiments board.

   `admin_experiments` is the collection behind admin/experiments.html and
   js/admin-experiments.js. This fills it with exactly two rows and their
   reels, and it exists for one reason, which is the same reason
   tools/seed-tasks.js exists: A BOARD THAT OPENS EMPTY TEACHES THE TWO PEOPLE
   LOOKING AT IT THAT THE BOARD IS SOMEWHERE WORK GOES TO BE FORGOTTEN, and
   they stop opening it in a week.

   TWO, AND NOT TWENTY. The real list is Hassan and Kathryn's to write. What
   these two are for is to show the shape: what a hypothesis reads like when
   it is written properly, what a decision rule is, what a reel row with its
   numbers in looks like, and — the part that matters most — what the board
   says when an experiment has ENDED and the difference between its two sides
   is still inside the noise. The second row below is deliberately that case,
   because the first thing anybody needs to learn from this surface is that
   two posts a side is not a result.

   IDEMPOTENT, AND THE KEY IS THE DOCUMENT ID. `x-hook-first-second` and
   `x-caption-style` are the ids; re-running finds them already there and
   creates nothing. create() and not set(), so a race with somebody typing on
   the board fails with ALREADY_EXISTS and is counted as skipped rather than
   overwriting an edit. AN EXISTING ROW IS NEVER UPDATED BY THIS TOOL — once
   an experiment is on the board it belongs to whoever is looking at it, and a
   seeder that reasserted its own idea of the title every run would silently
   undo them.

   WHY THE ID AND NOT A `seed` FIELD. firestore.rules enumerates the keys an
   experiment may have and one unlisted key denies the whole write — and on an
   update request.resource.data is the document AFTER the merge, so a
   twenty-fifth field written here would not sit there harmlessly: it would
   make every later edit from the browser fail with permission-denied, on rows
   that look perfectly normal. The id carries the key instead, and everything
   this tool writes is a shape the browser can go on editing.

   IT DOES NOT WRITE `createdBy`, deliberately, and for the reason
   tools/seed-tasks.js gives: a row generated by a script was not created by a
   person sitting at the board, and the detail view is entitled to say "not
   recorded" rather than naming anybody.

   IT DOES NOT WRITE AN `analysis` EITHER. That field is the WRITTEN READ — an
   opinion with a name and a clock on it — and a seeder that put words in
   somebody's mouth, signed by nobody, would be exactly the blurring of
   measurement and interpretation the whole surface is built to prevent. The
   two rows below carry `analysis: ""` and the page says nobody has written
   one.

   THE NUMBERS BELOW ARE PLAUSIBLE AND THEY ARE NOT REAL. They are shaped so
   the page's own arithmetic has something honest to chew on — one experiment
   that separates, one that does not — and every reel carries `postedAt` and
   `measuredAt` set at least 72 hours apart, because a seeded row that
   violated the one rule this board exists to enforce would teach the wrong
   thing on the first screen.

   CREDENTIALS. The service-account key at ~/.factbox-keys/admin.json, the
   same one tools/seed-tasks.js and tools/mint-promo-codes.js use, loaded the
   same way. It lives outside the repo and MUST NEVER BE COMMITTED. The admin
   SDK bypasses firestore.rules entirely, which is why every row below is
   validated here against the same enums and lengths the rules enforce: a row
   this tool waves through that the rules would refuse is a row the board can
   display and never edit.

   NOTE ON ORDER OF OPERATIONS. firestore.rules has NOT been deployed for this
   collection at the time of writing. The admin SDK does not care — it writes
   regardless — but the BROWSER will read nothing until the rules ship. If the
   page is empty after running this, deploy the rules; the data is there.

   Usage:
     node tools/seed-experiments.js --dry-run
     node tools/seed-experiments.js
   ========================================================================== */

